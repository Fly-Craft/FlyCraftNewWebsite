// Generates components/range-map-data.ts — world land projected with the
// same conic equal-area style as the site map, but framed wide enough that
// a full 3,200 NM range ring from any North American origin stays on the
// panel (reaching northern South America, Greenland and the mid-Atlantic).
// Keep the frame/params in sync with rangeProjection in lib/map-projection.ts.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { geoPath } from "d3-geo";
import { geoRobinson } from "d3-geo-projection";
import { feature } from "topojson-client";

const require = createRequire(import.meta.url);
const topo = JSON.parse(
  readFileSync(require.resolve("world-atlas/countries-110m.json"), "utf8")
);
const countries = feature(topo, topo.objects.countries).features;

const frame = {
  type: "MultiPoint",
  coordinates: [
    [-170, -35],
    [-10, -35],
    [-170, 74],
    [-10, 74],
  ],
};

const projection = geoRobinson()
  .rotate([90, 0])
  .fitExtent(
    [
      [30, 20],
      [1170, 780],
    ],
    frame
  )
  .clipExtent([
    [0, 0],
    [1200, 800],
  ]);

const path = geoPath(projection);
const round = (d) => d.replace(/-?\d+\.\d+/g, (m) => Number.parseFloat(m).toFixed(1));

const landPaths = [];
for (const c of countries) {
  const d = path(c);
  if (d) landPaths.push({ name: c.properties.name, d: round(d) });
}

// Sanity: full-ring bounding boxes for representative origins
const EARTH_NM = 3440.065;
function ringBBox(lat, lon, nm) {
  const δ = nm / EARTH_NM;
  const φ1 = (lat * Math.PI) / 180;
  const λ1 = (lon * Math.PI) / 180;
  let minX = 1e9, maxX = -1e9, minY = 1e9, maxY = -1e9;
  for (let i = 0; i <= 180; i++) {
    const θ = (i / 180) * 2 * Math.PI;
    const φ2 = Math.asin(Math.sin(φ1) * Math.cos(δ) + Math.cos(φ1) * Math.sin(δ) * Math.cos(θ));
    if ((φ2 * 180) / Math.PI > 79) continue; // arctic points wrap the antimeridian
    let λ2 = λ1 + Math.atan2(
      Math.sin(θ) * Math.sin(δ) * Math.cos(φ1),
      Math.cos(δ) - Math.sin(φ1) * Math.sin(φ2)
    );
    λ2 = ((λ2 + Math.PI) % (2 * Math.PI) + 2 * Math.PI) % (2 * Math.PI) - Math.PI;
    const p = projection([(λ2 * 180) / Math.PI, (φ2 * 180) / Math.PI]);
    if (!p || !Number.isFinite(p[0]) || !Number.isFinite(p[1])) continue;
    minX = Math.min(minX, p[0]); maxX = Math.max(maxX, p[0]);
    minY = Math.min(minY, p[1]); maxY = Math.max(maxY, p[1]);
  }
  return [minX, minY, maxX, maxY].map((v) => Math.round(v));
}
for (const [name, lat, lon] of [["TEB", 40.85, -74.06], ["LAX", 33.94, -118.41], ["OPF", 25.9, -80.28], ["YVR", 49.19, -123.18]]) {
  console.log(name, "3200NM ring bbox:", ringBBox(lat, lon, 3200).join(", "));
}

const out = `// AUTO-GENERATED by scripts/gen-range-map.mjs — do not edit by hand.
// World land (Natural Earth 110m) projected for the aircraft range map.
// ViewBox: 0 0 1200 800. Projection params live in lib/map-projection.ts
// (rangeProjection) — keep in sync with the generator.

export const RANGE_LAND_PATHS: { name: string; d: string }[] = ${JSON.stringify(landPaths)};
`;
writeFileSync(new URL("../components/range-map-data.ts", import.meta.url), out);
console.log(`Wrote ${landPaths.length} country paths.`);
